import makeWASocket, {
	Browsers,
	DisconnectReason,
	fetchLatestBaileysVersion,
	isJidGroup,
	isJidUser,
	jidNormalizedUser,
	useMultiFileAuthState
} from "@whiskeysockets/baileys";
import qrcode from "qrcode";
import pino from "pino";

import config from "../config";
import constants from "../constants";
import * as cli from "../cli/ui";
import { Message, createMessage, wasSentByBot } from "./message";

export interface WhatsAppHooks {
	onReady: () => void | Promise<void>;
	onMessage: (message: Message) => Promise<void>;
}

const reconnect = (hooks: WhatsAppHooks, delayMs = 3000) => {
	setTimeout(() => {
		startWhatsApp(hooks).catch((error) => {
			cli.printError(`[WhatsApp] Reconnect failed: ${error?.message || error}`);
			reconnect(hooks, 10000);
		});
	}, delayMs);
};

export async function startWhatsApp(hooks: WhatsAppHooks) {
	const { state, saveCreds } = await useMultiFileAuthState(config.sessionPath);

	let version: [number, number, number] | undefined;
	try {
		({ version } = await fetchLatestBaileysVersion());
	} catch {
		// Fall back to the version bundled with Baileys
	}

	const sock = makeWASocket({
		version,
		auth: state,
		browser: Browsers.ubuntu("Chrome"),
		logger: pino({ level: "warn" }),
		markOnlineOnConnect: false,
		syncFullHistory: false,
		generateHighQualityLinkPreview: true
	});

	let reconnectScheduled = false;

	sock.ev.on("creds.update", saveCreds);

	sock.ev.on("connection.update", async (update) => {
		const { connection, lastDisconnect, qr } = update;

		if (qr) {
			try {
				const terminalQr = await qrcode.toString(qr, { type: "terminal", small: true, margin: 2, scale: 1 });
				cli.printQRCode(terminalQr);
			} catch (error: any) {
				cli.printError(`[WhatsApp] Failed to render QR code: ${error?.message || error}`);
			}
		}

		if (connection === "open") {
			cli.printAuthenticated();
			await hooks.onReady();
		}

		if (connection === "close") {
			const statusCode = (lastDisconnect?.error as any)?.output?.statusCode;

			if (statusCode === DisconnectReason.loggedOut) {
				cli.printAuthenticationFailure();
				process.exit(1);
			}

			if (reconnectScheduled) return;
			reconnectScheduled = true;

			cli.printError(`[WhatsApp] Connection closed (${statusCode ?? "unknown"}). Reconnecting...`);
			reconnect(hooks, statusCode === DisconnectReason.restartRequired ? 500 : 3000);
		}
	});

	sock.ev.on("messages.upsert", async ({ messages, type }) => {
		if (type !== "notify") return;

		const selfJid = jidNormalizedUser(sock.user?.id);

		for (const raw of messages) {
			const from = raw.key.remoteJid;
			if (!from || from === constants.statusBroadcast) continue;

			const fromMe = !!raw.key.fromMe;

			// Ignore events generated by our own replies, but keep self-note messages
			if (fromMe && from !== selfJid) continue;
			if (wasSentByBot(raw.key.id)) continue;

			// Ignore broadcasts/newsletters, but allow users and groups
			if (!isJidUser(from) && !isJidGroup(from)) continue;

			const message = createMessage(sock, raw);
			if (!message.body && !message.hasMedia) continue;
			if (message.hasQuotedMsg) continue;

			try {
				await hooks.onMessage(message);
			} catch (error: any) {
				cli.printError(`[WhatsApp] Failed to handle message: ${error?.message || error}`);
			}
		}
	});

	return sock;
}
